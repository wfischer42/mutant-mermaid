/**
 * Writes advance-width tables for the bundled fonts to src/core/metrics/, so text can be measured
 * the same way in the browser and in Node, without a DOM or a font file at render time.
 */

import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as fontkit from 'fontkit'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** `name` is the table's export and file name; `id` is the FontId a theme names it by. */
const FONTS = [
  { id: 'nunito', name: 'nunito', pkg: '@fontsource/nunito', weights: [400, 500, 600, 700, 800] },
  { id: 'inter', name: 'inter', pkg: '@fontsource/inter', weights: [400, 500, 600, 700] },
  { id: 'plex', name: 'plex', pkg: '@fontsource/ibm-plex-sans', weights: [400, 500, 600, 700] },
  { id: 'dm-sans', name: 'dmSans', pkg: '@fontsource/dm-sans', weights: [400, 500, 600, 700] },
  {
    id: 'source-sans',
    name: 'sourceSans',
    pkg: '@fontsource/source-sans-3',
    weights: [400, 500, 600, 700],
  },
  { id: 'figtree', name: 'figtree', pkg: '@fontsource/figtree', weights: [400, 500, 600, 700] },
]

/** Basic Latin, Latin-1, Latin Extended-A and the punctuation and arrows diagrams use. */
const RANGES: [number, number][] = [
  [0x20, 0x7e],
  [0xa0, 0x17f],
  [0x2010, 0x2027],
  [0x2030, 0x203a],
  [0x2190, 0x2199],
  [0x2212, 0x2212],
  [0x2248, 0x2248],
  [0x2260, 0x2265],
]

function load({ pkg, subset, weight }: { pkg: string; subset: string; weight: number }) {
  const file = require.resolve(`${pkg}/files/${pkg.split('/')[1]}-${subset}-${weight}-normal.woff`)
  const font = fontkit.openSync(file)
  if (!('glyphForCodePoint' in font)) throw new Error(`${file} is a font collection`)
  return font
}

for (const font of FONTS) {
  const weights: Record<number, Record<string, number>> = {}
  let info = { unitsPerEm: 1000, ascent: 0, descent: 0, capHeight: 0, xHeight: 0 }
  for (const weight of font.weights) {
    const faces = ['latin', 'latin-ext'].map((subset) => load({ pkg: font.pkg, subset, weight }))
    const [main] = faces
    info = {
      unitsPerEm: main.unitsPerEm,
      ascent: main.ascent,
      descent: main.descent,
      capHeight: main.capHeight,
      xHeight: main.xHeight,
    }
    const widths: Record<string, number> = {}
    for (const [from, to] of RANGES) {
      for (let cp = from; cp <= to; cp++) {
        const face = faces.find((f) => f.hasGlyphForCodePoint(cp))
        if (!face) continue
        const advance = face.glyphForCodePoint(cp).advanceWidth
        widths[cp] = Math.round((advance / face.unitsPerEm) * 1000) / 1000
      }
    }
    weights[weight] = widths
  }
  const out = join(root, 'src/core/metrics', `${font.name}.ts`)
  const metrics = {
    id: font.id,
    ascent: info.ascent / info.unitsPerEm,
    descent: info.descent / info.unitsPerEm,
    capHeight: info.capHeight / info.unitsPerEm,
    xHeight: info.xHeight / info.unitsPerEm,
    weights,
  }
  writeFileSync(
    out,
    `// Generated by scripts/metrics.ts. Advance widths in em, by weight, then by code point.
import type { FontMetrics } from './types.ts'

export const ${font.name}: FontMetrics = ${JSON.stringify(metrics)}
`,
  )
  console.log(`wrote ${out}`)
}
